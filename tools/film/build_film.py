# 把开场片、片尾片和标题海报写进 echo.html 的 FILM 数据块（<!-- FILM-START --> … <!-- FILM-END -->），单个 html 离线也能放
# 运行：python tools/film/build_film.py [开场成片.mp4 片尾成片.mp4 海报.jpg]
#   带参数时先用 ffmpeg 重新压成 720p 存进 assets/film/；不带参数直接用 assets/film/ 里已有的文件
# 依赖：Pillow；带参数时还要 ffmpeg
import base64, io, os, re, subprocess, sys
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'film')
HTML = os.path.join(ROOT, 'echo.html')
CRF = 24   # 720p crf 24：两段合计约 4 MB；1080p 要多 1.6 MB，在游戏窗口里看不出差别

def encode(src, dst):
    subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', src, '-vf', 'scale=1280:-2:flags=lanczos', '-c:v', 'libx264',
                    '-preset', 'slow', '-crf', str(CRF), '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '112k',
                    '-movflags', '+faststart', dst], check=True)

def b64(path, mime):
    return f'data:{mime};base64,' + base64.b64encode(open(path, 'rb').read()).decode()

def main():
    os.makedirs(OUT, exist_ok=True)
    if len(sys.argv) == 4:
        encode(sys.argv[1], os.path.join(OUT, 'opening.mp4'))
        encode(sys.argv[2], os.path.join(OUT, 'ending.mp4'))
        im = Image.open(sys.argv[3]).convert('RGB'); im.thumbnail((1600, 900), Image.LANCZOS)
        im.save(os.path.join(OUT, 'poster.webp'), 'WEBP', quality=72, method=6)
    film = {'opening': b64(os.path.join(OUT, 'opening.mp4'), 'video/mp4'),
            'ending': b64(os.path.join(OUT, 'ending.mp4'), 'video/mp4'),
            'poster': b64(os.path.join(OUT, 'poster.webp'), 'image/webp')}
    js = 'const FILM = ' + '{' + ','.join(f'"{k}":"{v}"' for k, v in film.items()) + '};'
    block = f'<!-- FILM-START: generated by tools/film/build_film.py, do not edit -->\n<script>\n{js}\n</script>\n<!-- FILM-END -->'
    html = open(HTML, encoding='utf-8').read()
    if '<!-- FILM-START' in html:
        html = re.sub(r'<!-- FILM-START.*?<!-- FILM-END -->', lambda m: block, html, flags=re.S)
    else:
        i = html.index('<!-- ART-END -->') + len('<!-- ART-END -->'); html = html[:i] + '\n' + block + html[i:]
    open(HTML, 'w', encoding='utf-8').write(html)
    print(f'film {sum(len(v) for v in film.values()) / 1e6:.2f} MB, html {len(html.encode()) / 1e6:.2f} MB')

if __name__ == '__main__':
    main()
