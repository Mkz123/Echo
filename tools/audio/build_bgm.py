#!/usr/bin/env python3
"""
把五大场景的背景音乐压成高质量轻量 MP3，并以 base64 内嵌方式写入 echo.html 的 BGM 数据块
运行：python3 tools/audio/build_bgm.py
"""

import base64
import os
import re
import subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
AUDIO_DIR = os.path.join(ROOT, 'assets', 'audio')
HTML = os.path.join(ROOT, 'echo.html')

SCENES = [
    ('greenhouse', 'bgm_01_greenhouse'),
    ('workshop', 'bgm_02_workshop'),
    ('lab', 'bgm_03_lab'),
    ('bridge', 'bgm_04_bridge'),
    ('station', 'bgm_05_station'),
]

def encode_mp3(wav_path, mp3_path):
    # 使用 VBR qscale 4 压缩，兼顾高保真音质与轻量体积 (~400KB - 500KB)
    subprocess.run([
        'ffmpeg', '-y', '-v', 'error',
        '-i', wav_path,
        '-codec:a', 'libmp3lame',
        '-qscale:a', '4',
        mp3_path
    ], check=True)

def b64(path, mime='audio/mp3'):
    with open(path, 'rb') as f:
        data = f.read()
    return f'data:{mime};base64,' + base64.b64encode(data).decode('ascii')

def main():
    os.makedirs(AUDIO_DIR, exist_ok=True)
    bgm_dict = {}

    print("========================================")
    print("开始打包五大场景背景音乐到 echo.html")
    print("========================================")

    for scene_id, file_prefix in SCENES:
        wav_path = os.path.join(AUDIO_DIR, f"{file_prefix}.wav")
        mp3_path = os.path.join(AUDIO_DIR, f"{file_prefix}.mp3")

        if not os.path.exists(mp3_path) or os.path.getsize(mp3_path) > 1.2 * 1024 * 1024:
            print(f"压缩音频 {file_prefix} -> {mp3_path} ...")
            encode_mp3(wav_path, mp3_path)

        data_uri = b64(mp3_path, 'audio/mp3')
        bgm_dict[scene_id] = data_uri
        print(f"-> 场景 [{scene_id}]: {os.path.getsize(mp3_path) / 1024:.1f} KB (base64: {len(data_uri)/1024:.1f} KB)")

    js = 'const BGM = ' + '{' + ','.join(f'"{k}":"{v}"' for k, v in bgm_dict.items()) + '};'
    block = f'<!-- BGM-START: generated by tools/audio/build_bgm.py, do not edit -->\n<script>\n{js}\n</script>\n<!-- BGM-END -->'

    with open(HTML, 'r', encoding='utf-8') as f:
        html = f.read()

    if '<!-- BGM-START' in html:
        html = re.sub(r'<!-- BGM-START.*?<!-- BGM-END -->', lambda m: block, html, flags=re.S)
    elif '<!-- FILM-END -->' in html:
        idx = html.index('<!-- FILM-END -->') + len('<!-- FILM-END -->')
        html = html[:idx] + '\n' + block + html[idx:]
    else:
        idx = html.index('<!-- ART-END -->') + len('<!-- ART-END -->')
        html = html[:idx] + '\n' + block + html[idx:]

    with open(HTML, 'w', encoding='utf-8') as f:
        f.write(html)

    total_mb = sum(len(v) for v in bgm_dict.values()) / 1e6
    html_mb = len(html.encode('utf-8')) / 1e6
    print(f"\nBGM 数据块总计: {total_mb:.2f} MB, 打包后 echo.html 大小: {html_mb:.2f} MB")
    print("BGM 数据已成功写入 echo.html！")

if __name__ == '__main__':
    main()
