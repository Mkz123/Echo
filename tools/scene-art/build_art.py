# 把场景整景、格子位置和道具/47 精灵图压缩后写进 echo.html 的 ART 数据块（<!-- ART-START --> … <!-- ART-END -->）
# 运行：python tools/scene-art/build_art.py     依赖：Pillow
# 先跑 fit_anchors.py 生成 anchors.json；换了原画或手工位置后两步都要重跑
import base64, io, json, os, re
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BG = os.path.join(ROOT, 'assets', 'backgrounds-v3')
SP = os.path.join(ROOT, 'assets', 'map-study-v1', 'sprites')
HTML = os.path.join(ROOT, 'echo.html')
PX_PER_CELL = 80      # 背景每格像素：大关卡每格约 55–60 CSS px；原画细节多，再高单文件会超过 8 MB
SPRITES = ['plate-idle', 'plate-active', 'timed-idle', 'timed-active', 'box', 'door-closed', 'door-open',
           'inverse-closed', 'gate-ready', 'gate-used', 'robot-front', 'robot-left', 'robot-right', 'robot-back']
SCENES = ['greenhouse', 'workshop', 'lab', 'bridge', 'station']
XUYAO = os.path.join(ROOT, 'assets', 'characters', 'xuyao')   # 许遥四视图切图（front/left/right/back）
XUYAO_H = 320         # 绘制时约 70–90 CSS px 高，320 够 2x 屏

def webp(im, q):
    b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), b.tell()

def main():
    entries = json.load(open(os.path.join(BG, 'manifest.json')))['entries']
    anchors = json.load(open(os.path.join(ROOT, 'tools', 'scene-art', 'anchors.json')))
    art = {'use': {}, 'bg': {}, 'cells': {}, 'sprites': {}, 'xuyao': {}}
    total = 0
    for e in entries:
        art['use'][f"{e['level']}:{e['scene']}"] = e['key']
        k = e['key']
        if k in art['bg']: continue
        a = anchors[k]
        im = Image.open(os.path.join(BG, e['png'])).convert('RGB')
        W = min(im.width, a['w'] * PX_PER_CELL); im = im.resize((W, round(W * a['h'] / a['w'])), Image.LANCZOS)
        art['bg'][k], n = webp(im, 50); total += n
        art['cells'][k] = a['cells']
    bg_total = total
    for s in SCENES:
        art['sprites'][s] = {}
        for n in SPRITES:
            im = Image.open(os.path.join(SP, s, n + '.png')).convert('RGBA')
            im = im.crop(im.getbbox())          # 去掉透明边，绘制时按真实轮廓缩放
            art['sprites'][s][n], b = webp(im, 86); total += b
    for n in ['front', 'left', 'right', 'back']:
        im = Image.open(os.path.join(XUYAO, n + '.png')).convert('RGBA'); im = im.crop(im.getbbox())
        im = im.resize((round(im.width * XUYAO_H / im.height), XUYAO_H), Image.LANCZOS)
        art['xuyao'][n], b = webp(im, 86); total += b
    js = 'const ART = ' + json.dumps(art, ensure_ascii=False, separators=(',', ':')) + ';'
    block = f'<!-- ART-START: generated by tools/scene-art/build_art.py, do not edit -->\n<script>\n{js}\n</script>\n<!-- ART-END -->'
    html = open(HTML, encoding='utf-8').read()
    if '<!-- ART-START' in html:
        html = re.sub(r'<!-- ART-START.*?<!-- ART-END -->', lambda m: block, html, flags=re.S)
    else:
        i = html.index('<script>\n// CORE-START'); html = html[:i] + block + '\n' + html[i:]
    open(HTML, 'w', encoding='utf-8').write(html)
    print(f'backgrounds {len(art["bg"])}: {bg_total / 1e6:.2f} MB, sprites: {(total - bg_total) / 1e6:.2f} MB, html {len(html.encode()) / 1e6:.2f} MB')

if __name__ == '__main__':
    main()
